#!/usr/bin/env python3
"""Train the verified-alignment YelpChi RoBERTa + relation-aware PyG model.

This trainer deliberately refuses to run without a report generated by
verify_yelpchi_text_alignment.py with status=verified.  It is a known-node,
transductive benchmark: all topology can participate in message passing while
labels are used only for train loss, validation threshold selection, and one
final test report.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import platform
import random
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import numpy as np
import sklearn
import torch
from scipy import io, sparse
from sklearn.metrics import average_precision_score, f1_score, roc_auc_score
from sklearn.model_selection import StratifiedShuffleSplit
from sklearn.preprocessing import StandardScaler
from transformers import AutoModel, AutoTokenizer

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))
from ml.models.roberta_relation_gnn import RobertaRelationGNN

RELATIONS = {"rur": "net_rur", "rsr": "net_rsr", "rtr": "net_rtr"}


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def dump(path: Path, payload: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n")


def seed_everything(seed: int) -> None:
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)


def split_nodes(labels: np.ndarray, seed: int) -> dict[str, np.ndarray]:
    indices = np.arange(labels.shape[0])
    first = StratifiedShuffleSplit(n_splits=1, train_size=0.6, random_state=seed)
    train, held = next(first.split(indices, labels))
    second = StratifiedShuffleSplit(n_splits=1, train_size=0.5, random_state=seed + 1)
    validation_relative, test_relative = next(second.split(held, labels[held]))
    return {"train": np.sort(train), "validation": np.sort(held[validation_relative]), "test": np.sort(held[test_relative])}


def to_edges(value: Any, count: int) -> torch.Tensor:
    matrix = value.tocoo() if sparse.issparse(value) else sparse.coo_matrix(value)
    if matrix.shape != (count, count):
        raise ValueError(f"unexpected adjacency shape {matrix.shape}")
    return torch.from_numpy(np.vstack((matrix.row, matrix.col)).astype(np.int64)).contiguous()


def select_threshold(labels: np.ndarray, scores: np.ndarray) -> tuple[float, float]:
    best_threshold, best_score = 0.5, -1.0
    for threshold in np.linspace(0.01, 0.99, 199):
        score = f1_score(labels, scores >= threshold, average="macro", zero_division=0)
        if score > best_score:
            best_threshold, best_score = float(threshold), float(score)
    return best_threshold, best_score


def evaluate(labels: np.ndarray, scores: np.ndarray, threshold: float) -> dict[str, float]:
    return {
        "roc_auc": float(roc_auc_score(labels, scores)),
        "pr_auc": float(average_precision_score(labels, scores)),
        "f1_macro": float(f1_score(labels, scores >= threshold, average="macro", zero_division=0)),
        "threshold": threshold,
    }


def embed_text(texts: list[str], model_name: str, revision: str, batch_size: int, max_length: int, device: torch.device) -> tuple[torch.Tensor, dict[str, Any]]:
    tokenizer = AutoTokenizer.from_pretrained(model_name, revision=revision, use_fast=True)
    encoder = AutoModel.from_pretrained(model_name, revision=revision).to(device).eval()
    # A frozen encoder makes the benchmark practical on Kaggle and records a stable text feature artifact.
    chunks: list[torch.Tensor] = []
    with torch.inference_mode():
        for start in range(0, len(texts), batch_size):
            batch = tokenizer(texts[start:start + batch_size], truncation=True, padding=True, max_length=max_length, return_tensors="pt")
            batch = {name: value.to(device) for name, value in batch.items()}
            output = encoder(**batch).last_hidden_state
            mask = batch["attention_mask"].unsqueeze(-1)
            pooled = (output * mask).sum(dim=1) / mask.sum(dim=1).clamp_min(1)
            chunks.append(pooled.cpu().to(torch.float32))
    commit = getattr(encoder.config, "_commit_hash", None)
    if not commit:
        raise RuntimeError("Hugging Face did not expose a resolved immutable commit hash; pin --roberta-revision to a commit SHA")
    return torch.cat(chunks, dim=0), {"model_name": model_name, "requested_revision": revision, "resolved_revision": commit, "max_length": max_length, "pooling": "attention_masked_mean", "frozen": True}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--mat-path", required=True)
    parser.add_argument("--alignment-report", required=True)
    parser.add_argument("--alignment-csv", required=True)
    parser.add_argument("--output-root", required=True)
    parser.add_argument("--run-record-dir", required=True)
    parser.add_argument("--roberta-model", default="FacebookAI/roberta-base")
    parser.add_argument("--roberta-revision", required=True, help="Immutable Hugging Face commit SHA, never a mutable branch name")
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--hidden-dim", type=int, default=128)
    parser.add_argument("--dropout", type=float, default=0.2)
    parser.add_argument("--learning-rate", type=float, default=1e-3)
    parser.add_argument("--weight-decay", type=float, default=1e-4)
    parser.add_argument("--epochs", type=int, default=80)
    parser.add_argument("--patience", type=int, default=12)
    parser.add_argument("--text-batch-size", type=int, default=64)
    parser.add_argument("--max-length", type=int, default=192)
    parser.add_argument("--device", default="cuda")
    args = parser.parse_args()

    report_path, alignment_path, mat_path = Path(args.alignment_report).resolve(), Path(args.alignment_csv).resolve(), Path(args.mat_path).resolve()
    report = json.loads(report_path.read_text())
    if report.get("status") != "verified":
        raise ValueError("alignment report is not verified; training is forbidden")
    if report.get("alignment_sha256") != sha256(alignment_path) or report.get("mat_sha256") != sha256(mat_path):
        raise ValueError("alignment report hash bindings do not match current inputs")
    if args.device == "cuda" and not torch.cuda.is_available():
        raise RuntimeError("CUDA GPU is required for this multimodal Kaggle run")
    device = torch.device(args.device)
    seed_everything(args.seed)

    aligned = __import__("pandas").read_csv(alignment_path, dtype={"node_index": np.int64})
    required_columns = {"node_index", "review_id", "review_text", "label"}
    if required_columns.difference(aligned.columns) or not np.array_equal(aligned.node_index.to_numpy(), np.arange(len(aligned))):
        raise ValueError("alignment CSV is not a sorted exact node mapping")
    raw = io.loadmat(mat_path)
    metadata = raw["features"].toarray() if sparse.issparse(raw["features"]) else np.asarray(raw["features"])
    labels = np.asarray(raw["label"]).reshape(-1).astype(np.int64)
    if len(aligned) != len(labels) or not np.array_equal(aligned.label.to_numpy(dtype=np.int64), labels):
        raise ValueError("alignment labels fail exact MAT validation")
    splits = split_nodes(labels, args.seed)
    scaler = StandardScaler().fit(metadata[splits["train"]])
    x_meta_cpu = torch.from_numpy(scaler.transform(metadata).astype(np.float32))
    edges_cpu = {name: to_edges(raw[key], len(labels)) for name, key in RELATIONS.items()}
    x_text_cpu, tokenizer_config = embed_text(aligned.review_text.astype(str).tolist(), args.roberta_model, args.roberta_revision, args.text_batch_size, args.max_length, device)
    if x_text_cpu.shape != (len(labels), 768):
        raise ValueError(f"unexpected RoBERTa embedding shape {tuple(x_text_cpu.shape)}")

    run_id = f"yelpchi_multimodal_seed{args.seed}_{datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ')}"
    run_dir = Path(args.output_root).resolve() / run_id
    run_dir.mkdir(parents=True, exist_ok=False)
    config = {"schema_version": 1, "architecture": "frozen_roberta_relation_specific_pyg_graphsage_cross_attention", "text_dim": 768, "meta_dim": 32, "hidden_dim": args.hidden_dim, "dropout": args.dropout, "relations": list(RELATIONS), "tokenizer": tokenizer_config, "seed": args.seed, "evaluation_protocol": "transductive_known_node", "split": {"train": .6, "validation": .2, "test": .2, "seed": args.seed}, "alignment_report_sha256": sha256(report_path), "alignment_sha256": sha256(alignment_path)}
    dump(run_dir / "model_config.json", config)
    dump(run_dir / "preprocessing.json", {"schema_version": 1, "metadata_scaler": {"fitted_on_split": "train", "mean": scaler.mean_.tolist(), "scale": scaler.scale_.tolist()}, "text": tokenizer_config})
    graph = {"schema_version": 1, "review_ids": aligned.review_id.astype(str).tolist(), "x_text": x_text_cpu, "x_meta": x_meta_cpu, **{f"edge_index_{name}": edge for name, edge in edges_cpu.items()}}
    torch.save(graph, run_dir / "serving_graph.pt")
    np.savez_compressed(run_dir / "evaluation_targets.npz", labels=labels, **{f"{name}_indices": values for name, values in splits.items()})
    x_text, x_meta = x_text_cpu.to(device), x_meta_cpu.to(device)
    edges = {name: edge.to(device) for name, edge in edges_cpu.items()}
    y = torch.from_numpy(labels).long().to(device)
    split_tensors = {name: torch.from_numpy(values).long().to(device) for name, values in splits.items()}
    counts = np.bincount(labels[splits["train"]], minlength=2)
    loss_fn = torch.nn.CrossEntropyLoss(weight=torch.tensor(counts.sum() / (2 * counts), dtype=torch.float32, device=device))
    model = RobertaRelationGNN(hidden_dim=args.hidden_dim, dropout=args.dropout).to(device)
    optimizer = torch.optim.AdamW(model.parameters(), lr=args.learning_rate, weight_decay=args.weight_decay)
    best_state, best_epoch, best_f1, stale, log = None, -1, -1.0, 0, []
    for epoch in range(1, args.epochs + 1):
        model.train(); optimizer.zero_grad(set_to_none=True)
        loss = loss_fn(model(x_text, x_meta, edges)[split_tensors["train"]], y[split_tensors["train"]]); loss.backward(); optimizer.step()
        model.eval()
        with torch.inference_mode(): scores = torch.softmax(model(x_text, x_meta, edges), dim=1)[:, 1].cpu().numpy()
        threshold, val_f1 = select_threshold(labels[splits["validation"]], scores[splits["validation"]])
        log.append({"epoch": epoch, "train_loss": float(loss.item()), "validation_f1_macro": val_f1, "validation_threshold": threshold})
        if val_f1 > best_f1 + 1e-12:
            best_state, best_epoch, best_f1, stale = {k: v.detach().cpu().clone() for k, v in model.state_dict().items()}, epoch, val_f1, 0
        else:
            stale += 1
            if stale >= args.patience: break
    if best_state is None: raise RuntimeError("no checkpoint produced")
    model.load_state_dict(best_state); model.eval()
    with torch.inference_mode(): scores = torch.softmax(model(x_text, x_meta, edges), dim=1)[:, 1].cpu().numpy()
    threshold, validation_f1 = select_threshold(labels[splits["validation"]], scores[splits["validation"]])
    test_metrics = evaluate(labels[splits["test"]], scores[splits["test"]], threshold)
    torch.save({"state_dict": best_state, "model_config": config}, run_dir / "model_state.pt")
    dump(run_dir / "metrics.json", {"best_epoch": best_epoch, "best_validation_f1_macro": best_f1, "selected_validation_threshold": threshold, "validation_f1_at_selected_threshold": validation_f1, "test": test_metrics})
    dump(run_dir / "training_log.json", {"epochs": log})
    fixed_index = int(splits["test"][0])
    fixed = {"review_id": graph["review_ids"][fixed_index], "node_index": fixed_index, "expected_fraud_score": float(scores[fixed_index]), "tolerance": 1e-6, "labels_required_for_reproduction": False}
    dump(run_dir / "fixed_review_reproduction.json", fixed)
    files = ["model_state.pt", "model_config.json", "preprocessing.json", "serving_graph.pt", "evaluation_targets.npz", "metrics.json", "training_log.json", "fixed_review_reproduction.json"]
    manifest = {"schema_version": 1, "bundle_type": "yelpchi_multimodal_roberta_pyg_gnn", "provenance": "real_benchmark_data", "model_claim": "Frozen RoBERTa embeddings fused with relation-specific RUR/RSR/RTR PyG GraphSAGE", "run_id": run_id, "created_at_utc": datetime.now(timezone.utc).isoformat(), "dataset": {"mat_sha256": sha256(mat_path), "alignment_report_sha256": sha256(report_path), "alignment_sha256": sha256(alignment_path)}, "config": config, "threshold": threshold, "metrics": {"test": test_metrics}, "fixed_review": fixed, "environment": {"python": sys.version, "platform": platform.platform(), "torch": torch.__version__, "cuda": torch.version.cuda, "sklearn": sklearn.__version__}, "files": {name: sha256(run_dir / name) for name in files}}
    dump(run_dir / "run_manifest.json", manifest)
    manifest_hash = sha256(run_dir / "run_manifest.json")
    record = {"run_id": run_id, "bundle_manifest_sha256": manifest_hash, "model_claim": manifest["model_claim"], "evaluation_protocol": config["evaluation_protocol"], "selected_validation_threshold": threshold, "test_metrics": test_metrics, "bundle_location": str(run_dir), "reproduction_command": f"python ml/reproduce_yelpchi_multimodal_bundle.py --bundle-dir {run_dir} --manifest-sha256 {manifest_hash}"}
    dump(Path(args.run_record_dir).resolve() / f"{run_id}.json", record)
    print(json.dumps({"run_id": run_id, "bundle_dir": str(run_dir), "manifest_sha256": manifest_hash}, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
